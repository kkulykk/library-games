#!/usr/bin/env node
// Generates src/games/globetrotter/panoramaxCoverage.ts — the list of world
// cells where Panoramax actually holds 360° imagery.
//
// Panoramax's STAC search takes a bounding box, so Random World needs somewhere
// to point it. Drawing random land cells does not work: Panoramax is a young,
// volunteer-fed archive and most of the planet's land is empty, so four sweeps
// out of five would come back with nothing and the deck would fall to the
// offline reserve. This script probes a fixed grid once, offline, and vendors
// the cells that answered — turning a ~15% blind hit rate into a ~90% one.
//
// The probe is a single `limit=1` search per cell, so it is cheap for the
// server but slow by wall clock (it is deliberately paced). Like the reserve
// builder it is a manual, occasional job and is NOT wired into CI: its result
// depends on the live archive, not on the commit. Re-run it when Random World
// starts feeling repetitive — new instances join the federation regularly.
//
// Usage:
//   node scripts/generate-panoramax-coverage.mjs [cellDegrees]

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, '..', 'src', 'games', 'globetrotter', 'panoramaxCoverage.ts')

const API = 'https://api.panoramax.xyz/api/search'
/** Only equirectangular photospheres are playable — flat street shots are not. */
const SPHERICAL = 'field_of_view = 360'
const CELL = Number(process.argv[2] ?? 10)
/** Above/below these latitudes there is ice, ocean and no contributors. */
const LAT_MIN = -60
const LAT_MAX = 80
/** Probes in flight. Kept low — this is a volunteer-run server. */
const CONCURRENCY = 4
const PAUSE_MS = 120
const TIMEOUT_MS = 45000
const USER_AGENT = 'library-games-panoramax-coverage/1.0 (https://github.com/kkulykk/library-games)'

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

async function hasSpherical(lon, lat) {
  const query = new URLSearchParams({
    bbox: `${lon},${lat},${lon + CELL},${lat + CELL}`,
    limit: '1',
    filter: SPHERICAL,
  })
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const response = await fetch(`${API}?${query}`, {
        headers: { 'user-agent': USER_AGENT },
        signal: AbortSignal.timeout(TIMEOUT_MS),
      })
      if (!response.ok) throw new Error(`Panoramax API ${response.status}`)
      const body = await response.json()
      return (body.features ?? []).length > 0
    } catch (error) {
      if (attempt === 2) {
        console.error(`  ${lon},${lat} failed: ${error.message}`)
        return false
      }
      await sleep(2000 * (attempt + 1))
    }
  }
  return false
}

function grid() {
  const cells = []
  for (let lon = -180; lon < 180; lon += CELL) {
    for (let lat = LAT_MIN; lat < LAT_MAX; lat += CELL) {
      cells.push([lon, lat])
    }
  }
  return cells
}

async function probeAll(cells) {
  const covered = []
  let cursor = 0
  let done = 0
  async function worker() {
    while (cursor < cells.length) {
      const [lon, lat] = cells[cursor++]
      const hit = await hasSpherical(lon, lat)
      done += 1
      if (hit) covered.push([lon, lat])
      if (done % 25 === 0) console.error(`  ${done}/${cells.length} probed, ${covered.length} hits`)
      await sleep(PAUSE_MS)
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker))
  // Workers finish out of order; a stable file keeps diffs readable.
  return covered.sort((a, b) => a[0] - b[0] || a[1] - b[1])
}

function emit(cells) {
  const rows = cells.map(([lon, lat]) => `  [${lon}, ${lat}],`).join('\n')
  return `// Where Panoramax holds 360° imagery — generated by
// scripts/generate-panoramax-coverage.mjs. Do not hand-edit.
//
// Each entry is the south-west corner of a ${CELL}°×${CELL}° cell that answered a
// spherical-picture search when the grid was last probed. Random World aims its
// Panoramax sweeps at these cells instead of at random land, which is what
// keeps the hit rate high enough to be worth a request.
//
// A stale cell costs one empty sweep, never a broken round — so this list may
// lag the archive without hurting anything.

/** Cell size in degrees; a cell is [west, south] to [west + size, south + size]. */
export const PANORAMAX_CELL_DEGREES = ${CELL}

/** South-west corners of the cells known to hold spherical pictures. */
export const PANORAMAX_COVERAGE: readonly (readonly [number, number])[] = [
${rows}
]
`
}

async function main() {
  const cells = grid()
  console.error(`probing ${cells.length} cells of ${CELL}°…`)
  const covered = await probeAll(cells)
  writeFileSync(OUT, emit(covered))
  console.error(`wrote ${covered.length} covered cells to ${OUT}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main()
}
